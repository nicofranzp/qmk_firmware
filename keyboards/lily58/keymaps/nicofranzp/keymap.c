// Add after keymaps
uint16_t get_tapping_term(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case HOME_F:
        case HOME_J:
            return TAPPING_TERM * 0.8;  // 80% of global tapping term
        default:
            return TAPPING_TERM;
    }
}

