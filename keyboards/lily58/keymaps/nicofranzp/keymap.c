void add_keylog(uint16_t keycode) {
    if ((keycode >= QK_MOD_TAP && keycode <= QK_MOD_TAP_MAX) || (keycode >= QK_LAYER_TAP && keycode <= QK_LAYER_TAP_MAX)) {
        keycode = keycode & 0xFF;
    }

    for (uint8_t i = KEYLOG_LEN - 1; i > 0; i--) {
        keylog_str[i] = keylog_str[i - 1];
    }
    if (keycode < 60) {
        keylog_str[0] = code_to_name[keycode];
    }
    keylog_str[KEYLOG_LEN - 1] = 0;

    log_timer = timer_read();
}

void update_log(void) {
    if (timer_elapsed(log_timer) > 750) {
        add_keylog(0);
    }
}

void render_keylogger_status(void) {
    oled_write_P(PSTR("K-log"), false);
    oled_write(keylog_str, false);
}

void render_default_layer_state(void) {
    oled_set_cursor(0, 0);
    oled_write_ln_P(PSTR("Layer"), false);
    oled_set_cursor(0, 2);
    switch (get_highest_layer(layer_state)) {
        case _QWERTY:
                draw_layer_icon(qwerty_icon);
                break;
            case _SYMBOLS:
                draw_layer_icon(symbol_icon);
                break;
            case _ARROWS:
                draw_layer_icon(arrow_icon);
                break;
            case _NUMPAD:
                draw_layer_icon(numpad_icon);
                break;
            case _MOUSE:
                draw_layer_icon(mouse_icon);
                break;
        default:
            oled_write_ln_P(PSTR("Undefined"), false);
    }
}

void render_mod_status(uint8_t modifiers) {
    oled_write_ln_P(PSTR("Mods"), false);
    oled_write_ln_P(PSTR(""), false);
    oled_write_P(PSTR(" "), false);
    oled_write_P(PSTR("S"), (modifiers & MOD_MASK_SHIFT));
    oled_write_P(PSTR("C"), (modifiers & MOD_MASK_CTRL));
    oled_write_P(PSTR("A"), (modifiers & MOD_MASK_ALT));
    oled_write_P(PSTR("G"), (modifiers & MOD_MASK_GUI));
}

void render_status_main(void) {
    //Show keyboard layout
    // oled_set_cursor(0,0);
    render_default_layer_state();
    // Show modifier status
    oled_set_cursor(0,8);
    render_mod_status(get_mods());

    // Key Log
    oled_set_cursor(0,13);
    render_keylogger_status();
}

bool oled_task_user(void) {
  update_log();
  if (is_keyboard_master()) {
    render_status_main();
  } else {
    render_lily58_logo();
  }
    return false;
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        add_keylog(keycode);
    }
    switch (keycode) {
        case MAC_BOL:
            if (record->event.pressed) {
                tap_code16(LGUI(KC_LEFT));  // Command + Left Arrow
            }
            return false;
        case MAC_EOL:
            if (record->event.pressed) {
                tap_code16(LGUI(KC_RIGHT)); // Command + Right Arrow
            }
            return false;
    }
    return true;
}
